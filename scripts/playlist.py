"""Datasource model: datasource/*.m3u are the source of truth; official.m3u is generated from them."""
from __future__ import annotations

import os
import re
import unicodedata
from dataclasses import dataclass, field

from streams import canonical_url, is_astra_play_url

REPO_ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
DATASOURCE_DIR = os.path.join(REPO_ROOT, "datasource")
OFFICIAL_PATH = os.path.join(REPO_ROOT, "official.m3u")
BACKUP_PATH = os.path.join(REPO_ROOT, "backup.m3u")
GENERATED_HEADER = "# GENERATED by scripts/iptv.py build from datasource/ - DO NOT EDIT"
EXTINF_PREFIX = "#EXTINF:-1,"
# SS IPTV defaults to Spanish and shows the language menu only when this is set on Astra streams.
SSIPTV_AUDIO_TRACK = "spa,eng"
GENERATED_NAME_RE = re.compile(r"^\d+\s+.+\s+\d+$")


class PlaylistError(Exception):
    """Invalid datasource content or an operation that cannot be applied safely."""


@dataclass(frozen=True)
class Section:
    key: str
    title: str

    @property
    def path(self) -> str:
        return os.path.join(DATASOURCE_DIR, f"{self.key}.m3u")


SECTIONS = (
    Section("nacionales", "Nacionales"),
    Section("noticias", "Noticias"),
    Section("infantiles", "Infantiles"),
    Section("peliculas", "Peliculas"),
    Section("series", "Series"),
    Section("deportes", "Deportes"),
    Section("musica", "Musica"),
    Section("documentales", "Documentales"),
    Section("variedades", "Variedades"),
    Section("internacionales", "Internacionales"),
    Section("experimentales", "24/7 - Experimentales"),
)


@dataclass(eq=False)
class Entry:
    name: str
    url: str
    options: list[str] = field(default_factory=list)


@dataclass(frozen=True)
class Channel:
    """An entry plus the global ID and repetition index it gets in official.m3u."""

    channel_id: int
    repetition: int
    section: Section
    entry: Entry

    @property
    def label(self) -> str:
        return f"{self.channel_id} {self.entry.name} {self.repetition}"

    def to_dict(self) -> dict:
        return {
            "id": self.channel_id,
            "channel": self.label,
            "section": self.section.key,
            "url": self.entry.url,
        }


class Playlist:
    def __init__(self, entries_by_section: dict):
        self.entries_by_section = entries_by_section

    @classmethod
    def load(cls) -> Playlist:
        expected_files = {f"{section.key}.m3u" for section in SECTIONS}
        unknown_files = sorted(set(os.listdir(DATASOURCE_DIR)) - expected_files)
        if unknown_files:
            raise PlaylistError(
                f"unknown files in datasource/: {', '.join(unknown_files)} "
                f"(valid sections: {', '.join(sorted(expected_files))})"
            )
        return cls({section: parse_section_file(section.path) for section in SECTIONS})

    def channels(self) -> list[Channel]:
        channels: list[Channel] = []
        repetitions: dict = {}
        for section in SECTIONS:
            for entry in self.entries_by_section[section]:
                repetitions[entry.name] = repetitions.get(entry.name, 0) + 1
                channels.append(Channel(len(channels) + 1, repetitions[entry.name], section, entry))
        return channels

    def channel(self, channel_id: int) -> Channel:
        for channel in self.channels():
            if channel.channel_id == channel_id:
                return channel
        raise PlaylistError(f"ID {channel_id} does not exist in official.m3u")

    def channel_of(self, entry: Entry) -> Channel:
        return next(channel for channel in self.channels() if channel.entry is entry)

    def find_by_name(self, name: str) -> list[Channel]:
        wanted = name.casefold()
        return [channel for channel in self.channels() if channel.entry.name.casefold() == wanted]

    def position_after(self, anchor: Entry) -> tuple[Section, int]:
        section = self.channel_of(anchor).section
        return section, self._index_in_section(section, anchor) + 1

    def insert(self, entry: Entry, section: Section, index: int) -> None:
        self.entries_by_section[section].insert(index, entry)

    def remove(self, entry: Entry) -> None:
        section = self.channel_of(entry).section
        del self.entries_by_section[section][self._index_in_section(section, entry)]

    def save(self) -> None:
        for section in SECTIONS:
            write_section_file(section, self.entries_by_section[section])

    def _index_in_section(self, section: Section, entry: Entry) -> int:
        entries = self.entries_by_section[section]
        return next(index for index, candidate in enumerate(entries) if candidate is entry)


def resolve_section(raw_name: str) -> Section:
    wanted = normalize_text(raw_name)
    for section in SECTIONS:
        if wanted in (section.key, normalize_text(section.title)):
            return section
    raise PlaylistError(
        f"unknown section '{raw_name}' (valid: {', '.join(section.key for section in SECTIONS)})"
    )


def validate_channel_name(name: str) -> None:
    if not name:
        raise PlaylistError("channel name is empty")
    if '"' in name:
        raise PlaylistError(f"channel name '{name}' must not contain double quotes")
    if GENERATED_NAME_RE.match(name):
        raise PlaylistError(
            f"channel name '{name}' looks like a generated '<id> <name> <rep>' label; "
            "store only the clean name"
        )


def render_official(playlist: Playlist, logo_by_channel: dict) -> tuple[str, list[str]]:
    """Return the official.m3u content and the channel names that have no logo."""
    channels = playlist.channels()
    ensure_unique_urls(channels)

    lines = ["#EXTM3U", GENERATED_HEADER]
    current_section = None
    for channel in channels:
        if channel.section != current_section:
            current_section = channel.section
            lines += ["", f"# ===== {current_section.title} =====", ""]
        logo = logo_by_channel.get(channel.entry.name, "")
        lines.append(render_extinf(channel.entry, channel.label, channel.section, logo))
        lines += channel.entry.options
        lines += [channel.entry.url, ""]

    names_without_logo = sorted({c.entry.name for c in channels if c.entry.name not in logo_by_channel})
    return "\n".join(lines).rstrip("\n") + "\n", names_without_logo


def append_to_backup(channels: list[Channel], logo_by_channel: dict) -> list[Channel]:
    """Append channels at the end of backup.m3u without reformatting it; return the ones skipped."""
    with open(BACKUP_PATH, encoding="utf-8") as handle:
        content = handle.read()
    existing_urls = {
        canonical_url(line) for line in content.splitlines() if line.strip() and not line.startswith("#")
    }

    blocks: list[str] = []
    skipped: list[Channel] = []
    for channel in channels:
        if canonical_url(channel.entry.url) in existing_urls:
            skipped.append(channel)
            continue
        logo = logo_by_channel.get(channel.entry.name, "")
        extinf = render_extinf(channel.entry, channel.entry.name, channel.section, logo)
        blocks.append("\n".join([extinf, *channel.entry.options, channel.entry.url]))

    if blocks:
        with open(BACKUP_PATH, "w", encoding="utf-8") as handle:
            handle.write(content.rstrip("\n") + "\n\n" + "\n\n".join(blocks) + "\n")
    return skipped


def ensure_unique_urls(channels: list[Channel]) -> None:
    first_by_url: dict = {}
    duplicates: list[str] = []
    for channel in channels:
        key = canonical_url(channel.entry.url)
        if key in first_by_url:
            duplicates.append(f"'{channel.label}' repeats the URL of '{first_by_url[key].label}'")
        else:
            first_by_url[key] = channel
    if duplicates:
        raise PlaylistError("duplicate stream URLs: " + "; ".join(duplicates))


def render_extinf(entry: Entry, label: str, section: Section, logo: str) -> str:
    attributes = [f'tvg-name="{label}"']
    if logo:
        attributes.append(f'tvg-logo="{logo}"')
    attributes.append(f'group-title="{section.title}"')
    if is_astra_play_url(entry.url):
        attributes.append(f'audio-track="{SSIPTV_AUDIO_TRACK}"')
    return f"#EXTINF:-1 {' '.join(attributes)},{label}"


def parse_section_file(path: str) -> list[Entry]:
    if not os.path.exists(path):
        raise PlaylistError(f"missing datasource file {os.path.relpath(path, REPO_ROOT)}")

    entries: list[Entry] = []
    pending_name = None
    options: list[str] = []
    location = os.path.relpath(path, REPO_ROOT)
    with open(path, encoding="utf-8") as handle:
        for line_number, raw_line in enumerate(handle, start=1):
            line = raw_line.strip()
            where = f"{location}:{line_number}"
            if not line or line == "#EXTM3U":
                continue
            if line.startswith("#EXTINF"):
                if pending_name is not None:
                    raise PlaylistError(f"{where}: previous #EXTINF has no URL")
                pending_name = parse_entry_name(line, where)
                options = []
            elif line.startswith("#EXTVLCOPT:") and pending_name is not None:
                options.append(line)
            elif line.startswith("#"):
                raise PlaylistError(
                    f"{where}: unexpected line (only #EXTINF, #EXTVLCOPT and URLs are allowed)"
                )
            elif pending_name is None:
                raise PlaylistError(f"{where}: URL without a preceding #EXTINF")
            else:
                entries.append(Entry(pending_name, line, options))
                pending_name = None
    if pending_name is not None:
        raise PlaylistError(f"{location}: last #EXTINF has no URL")
    return entries


def parse_entry_name(extinf: str, where: str) -> str:
    if not extinf.startswith(EXTINF_PREFIX):
        raise PlaylistError(
            f"{where}: use '{EXTINF_PREFIX}<name>' (tvg-name, tvg-logo, group-title and "
            "audio-track are generated by the build)"
        )
    name = extinf[len(EXTINF_PREFIX):].strip()
    try:
        validate_channel_name(name)
    except PlaylistError as exc:
        raise PlaylistError(f"{where}: {exc}") from None
    return name


def write_section_file(section: Section, entries: list[Entry]) -> None:
    blocks = ["#EXTM3U"]
    blocks += ["\n".join([EXTINF_PREFIX + entry.name, *entry.options, entry.url]) for entry in entries]
    with open(section.path, "w", encoding="utf-8") as handle:
        handle.write("\n\n".join(blocks) + "\n")


def normalize_text(value: str) -> str:
    decomposed = unicodedata.normalize("NFKD", value.strip().casefold())
    return "".join(char for char in decomposed if not unicodedata.combining(char))
